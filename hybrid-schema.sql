--
-- CueStack Hybrid Schema
-- 基于 slack-clone 架构 + Telegram 风格消息状态机
-- 目标：保留 slack-clone 的性能优化，添加 Agent 支持和消息状态追踪
--

-- ============================================
-- Custom types
-- ============================================
create type public.app_permission as enum ('channels.delete', 'messages.delete', 'agents.manage');
create type public.app_role as enum ('admin', 'moderator');
create type public.user_status as enum ('ONLINE', 'OFFLINE', 'AWAY');
create type public.message_status as enum ('SENDING', 'SENT', 'DELIVERED', 'READ', 'FAILED');
create type public.participant_type as enum ('human', 'agent');

-- ============================================
-- USERS (基于 slack-clone)
-- ============================================
create table public.users (
  id          uuid references auth.users not null primary key,
  username    text,
  display_name text,
  avatar_url  text,
  status      user_status default 'OFFLINE'::public.user_status,
  last_seen_at timestamp with time zone,
  created_at  timestamp with time zone default timezone('utc'::text, now()) not null
);
comment on table public.users is 'Human participants (profile data for each user).';
comment on column public.users.id is 'References the internal Supabase Auth user.';

-- ============================================
-- AGENTS (新增：Agent 参与者)
-- ============================================
create table public.agents (
  id            uuid primary key default gen_random_uuid(),
  owner_id      uuid references public.users on delete cascade not null,
  agent_name    text not null,
  display_name  text,
  avatar_url    text,
  runtime       text,  -- windsurf, cursor, etc.
  status        user_status default 'OFFLINE'::public.user_status,
  last_seen_at  timestamp with time zone,
  metadata      jsonb,  -- {project_dir, terminal, etc.}
  created_at    timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at    timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(owner_id, agent_name)
);
comment on table public.agents is 'AI Agent participants owned by users.';
create index idx_agents_owner on agents(owner_id);

-- ============================================
-- CHANNELS (基于 slack-clone，重命名概念为 conversations)
-- ============================================
create table public.channels (
  id            bigint generated by default as identity primary key,
  inserted_at   timestamp with time zone default timezone('utc'::text, now()) not null,
  slug          text not null unique,
  created_by_type participant_type not null,
  created_by_id   uuid not null,
  type          text default 'direct',  -- 'direct' | 'group'
  title         text,
  last_message_at timestamp with time zone
);
comment on table public.channels is 'Conversations (direct or group chat).';
create index idx_channels_created_by on channels(created_by_type, created_by_id);

-- ============================================
-- CHANNEL PARTICIPANTS (新增：对话参与者)
-- ============================================
create table public.channel_participants (
  id              bigint generated by default as identity primary key,
  channel_id      bigint references public.channels on delete cascade not null,
  participant_type participant_type not null,
  participant_id  uuid not null,
  joined_at       timestamp with time zone default timezone('utc'::text, now()) not null,
  last_read_at    timestamp with time zone,
  unique(channel_id, participant_type, participant_id)
);
comment on table public.channel_participants is 'Participants in each conversation.';
create index idx_channel_participants_channel on channel_participants(channel_id);
create index idx_channel_participants_participant on channel_participants(participant_type, participant_id);

-- ============================================
-- MESSAGES (扩展 slack-clone，添加状态机)
-- ============================================
create table public.messages (
  id              bigint generated by default as identity primary key,
  inserted_at     timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at      timestamp with time zone default timezone('utc'::text, now()) not null,
  message         text,
  payload         jsonb,  -- 结构化交互 {type: 'choice'|'confirm'|'form', ...}
  sender_type     participant_type not null,
  sender_id       uuid not null,
  channel_id      bigint references public.channels on delete cascade not null,
  status          message_status default 'SENT'::public.message_status,
  reply_to_message_id bigint references public.messages,
  edited_at       timestamp with time zone
);
comment on table public.messages is 'Individual messages with Telegram-style status tracking.';
create index idx_messages_channel on messages(channel_id, inserted_at desc);
create index idx_messages_sender on messages(sender_type, sender_id);

-- ============================================
-- MESSAGE RECEIPTS (新增：Telegram 风格送达/已读状态)
-- ============================================
create table public.message_receipts (
  id              bigint generated by default as identity primary key,
  message_id      bigint references public.messages on delete cascade not null,
  participant_type participant_type not null,
  participant_id  uuid not null,
  delivered_at    timestamp with time zone,
  read_at         timestamp with time zone,
  created_at      timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(message_id, participant_type, participant_id)
);
comment on table public.message_receipts is 'Message delivery and read receipts (Telegram-style).';
create index idx_message_receipts_message on message_receipts(message_id);

-- ============================================
-- FILES (新增：文件存储)
-- ============================================
create table public.files (
  id              uuid primary key default gen_random_uuid(),
  sha256          text unique not null,
  storage_path    text not null,
  filename        text not null,
  mime_type       text not null,
  size_bytes      bigint not null,
  uploaded_by_type participant_type not null,
  uploaded_by_id  uuid not null,
  created_at      timestamp with time zone default timezone('utc'::text, now()) not null
);
comment on table public.files is 'File attachments stored in Supabase Storage.';

-- ============================================
-- MESSAGE FILES (新增：消息-文件关联)
-- ============================================
create table public.message_files (
  message_id      bigint references public.messages on delete cascade not null,
  file_id         uuid references public.files on delete cascade not null,
  idx             integer not null,
  primary key (message_id, idx)
);
comment on table public.message_files is 'Links files to messages.';

-- ============================================
-- USER ROLES (保留 slack-clone RBAC)
-- ============================================
create table public.user_roles (
  id        bigint generated by default as identity primary key,
  user_id   uuid references public.users on delete cascade not null,
  role      app_role not null,
  unique (user_id, role)
);
comment on table public.user_roles is 'Application roles for each user.';

-- ============================================
