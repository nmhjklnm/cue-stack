-- RBAC authorize function (保留 slack-clone)
create function public.authorize(
  requested_permission app_permission
)
returns boolean as $$
declare
  bind_permissions int;
begin
  select count(*)
  from public.role_permissions
  where role_permissions.permission = authorize.requested_permission
    and role_permissions.role = (auth.jwt() ->> 'user_role')::public.app_role
  into bind_permissions;
  
  return bind_permissions > 0;
end;
$$ language plpgsql security definer set search_path = public;

-- Handle new user (保留 slack-clone)
create function public.handle_new_user() 
returns trigger as $$
declare is_admin boolean;
begin
  insert into public.users (id, username, display_name)
  values (new.id, new.email, split_part(new.email, '@', 1));
  
  select count(*) = 1 from auth.users into is_admin;
  
  if position('+supaadmin@' in new.email) > 0 then
    insert into public.user_roles (user_id, role) values (new.id, 'admin');
  elsif position('+supamod@' in new.email) > 0 then
    insert into public.user_roles (user_id, role) values (new.id, 'moderator');
  end if;
  
  return new;
end;
$$ language plpgsql security definer set search_path = auth, public;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Update channel timestamp on new message
create function public.update_channel_timestamp()
returns trigger as $$
begin
  update public.channels
  set last_message_at = now()
  where id = new.channel_id;
  return new;
end;
$$ language plpgsql;

create trigger on_message_insert
  after insert on public.messages
  for each row execute function public.update_channel_timestamp();

-- Auto-create message receipts for all participants (Telegram 风格)
create function public.create_message_receipts()
returns trigger as $$
begin
  insert into public.message_receipts (message_id, participant_type, participant_id)
  select new.id, cp.participant_type, cp.participant_id
  from public.channel_participants cp
  where cp.channel_id = new.channel_id
    and not (cp.participant_type = new.sender_type and cp.participant_id = new.sender_id);
  return new;
end;
$$ language plpgsql;

create trigger on_message_create_receipts
  after insert on public.messages
  for each row execute function public.create_message_receipts();

