-- Users: 所有认证用户可读，只能更新自己
create policy "Allow logged-in read access" on public.users for select using ( auth.role() = 'authenticated' );
create policy "Allow individual insert access" on public.users for insert with check ( auth.uid() = id );
create policy "Allow individual update access" on public.users for update using ( auth.uid() = id );

-- Agents: 只能操作自己拥有的 agent
create policy "Allow logged-in read access" on public.agents for select using ( auth.role() = 'authenticated' );
create policy "Allow owner CRUD access" on public.agents for all using ( auth.uid() = owner_id );

-- Channels: 所有认证用户可读（简化版，类似 slack-clone）
create policy "Allow logged-in read access" on public.channels for select using ( auth.role() = 'authenticated' );
create policy "Allow individual insert access" on public.channels for insert with check ( 
  (created_by_type = 'human' and auth.uid() = created_by_id)
);
create policy "Allow creator delete access" on public.channels for delete using ( 
  (created_by_type = 'human' and auth.uid() = created_by_id)
);
create policy "Allow authorized delete access" on public.channels for delete using ( authorize('channels.delete') );

-- Channel Participants: 所有认证用户可读
create policy "Allow logged-in read access" on public.channel_participants for select using ( auth.role() = 'authenticated' );
create policy "Allow insert for channel members" on public.channel_participants for insert with check ( auth.role() = 'authenticated' );

-- Messages: 所有认证用户可读（简化版，类似 slack-clone）
create policy "Allow logged-in read access" on public.messages for select using ( auth.role() = 'authenticated' );
create policy "Allow individual insert access" on public.messages for insert with check ( 
  (sender_type = 'human' and auth.uid() = sender_id)
  or
  (sender_type = 'agent' and exists (
    select 1 from public.agents a
    where a.id = sender_id and a.owner_id = auth.uid()
  ))
);
create policy "Allow individual update access" on public.messages for update using ( 
  (sender_type = 'human' and auth.uid() = sender_id)
);
create policy "Allow individual delete access" on public.messages for delete using ( 
  (sender_type = 'human' and auth.uid() = sender_id)
);
create policy "Allow authorized delete access" on public.messages for delete using ( authorize('messages.delete') );

-- Message Receipts: 所有认证用户可读
create policy "Allow logged-in read access" on public.message_receipts for select using ( auth.role() = 'authenticated' );
create policy "Allow update own receipts" on public.message_receipts for update using ( 
  (participant_type = 'human' and auth.uid() = participant_id)
);

-- Files: 所有认证用户可读
create policy "Allow logged-in read access" on public.files for select using ( auth.role() = 'authenticated' );
create policy "Allow individual insert access" on public.files for insert with check ( 
  (uploaded_by_type = 'human' and auth.uid() = uploaded_by_id)
  or
  (uploaded_by_type = 'agent' and exists (
    select 1 from public.agents a
    where a.id = uploaded_by_id and a.owner_id = auth.uid()
  ))
);

-- Message Files: 所有认证用户可读
create policy "Allow logged-in read access" on public.message_files for select using ( auth.role() = 'authenticated' );

-- User Roles: 只能读取自己的角色
create policy "Allow individual read access" on public.user_roles for select using ( auth.uid() = user_id );

