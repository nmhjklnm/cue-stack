-- Create test user (保留 slack-clone)
create or replace function public.create_user(
    email text
) returns uuid
    security definer
    set search_path = auth
as $$
  declare
  user_id uuid;
begin
  user_id := extensions.uuid_generate_v4();
  
  insert into auth.users (id, email)
    values (user_id, email)
    returning id into user_id;

    return user_id;
end;
$$ language plpgsql;

-- Get or create direct conversation between user and agent
create or replace function public.get_or_create_direct_conversation(
  p_user_id uuid,
  p_agent_id uuid
) returns bigint
language plpgsql
security definer
as $$
declare
  v_channel_id bigint;
begin
  -- Try to find existing direct conversation
  select c.id into v_channel_id
  from public.channels c
  where c.type = 'direct'
    and exists (
      select 1 from public.channel_participants cp1
      where cp1.channel_id = c.id
        and cp1.participant_type = 'human'
        and cp1.participant_id = p_user_id
    )
    and exists (
      select 1 from public.channel_participants cp2
      where cp2.channel_id = c.id
        and cp2.participant_type = 'agent'
        and cp2.participant_id = p_agent_id
    )
  limit 1;

  -- Create if not exists
  if v_channel_id is null then
    insert into public.channels (slug, created_by_type, created_by_id, type)
    values (
      'direct-' || p_user_id::text || '-' || p_agent_id::text,
      'human',
      p_user_id,
      'direct'
    )
    returning id into v_channel_id;

    -- Add participants
    insert into public.channel_participants (channel_id, participant_type, participant_id)
    values 
      (v_channel_id, 'human', p_user_id),
      (v_channel_id, 'agent', p_agent_id);
  end if;

  return v_channel_id;
end;
$$;
